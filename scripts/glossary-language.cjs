function polishMeaning(id,term,meaning){
 if(overrides[id])return overrides[id];
 const base=term.replace(/\s*\([^)]*\).*$/,'').trim();
 const particle=hasBatchim(base)?'은':'는';
 let result=meaning.replace(new RegExp(`^${escapeRegExp(term)}[은는](?=\\s)`),`${term}${particle}`)
  .replace(/메세지/g,'메시지')
  .replace(/주고 받을/g,'주고받을')
  .replace(/페이지 가/g,'페이지가')
  .replace(/통신과정/g,'통신 과정')
  .replace(/연결상에서/g,'연결에서')
  .replace(/포트번호/g,'포트 번호')
  .replace(/로 구성해요/g,'로 구성돼요');
 for(const [pattern,replacement] of endingRewrites)result=result.replace(pattern,replacement);
 return result;
}

function polishTerm(id,term){return termOverrides[id]||term;}

